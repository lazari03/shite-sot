#!/usr/bin/env bash
# Another reverse proxy (e.g. your other site's Caddy container) already owns ports 80/443.
# Instead of fighting for the ports: join its Docker network and add a site block to its Caddyfile.
# Usage: use-existing-proxy.sh <proxy-container> <domain> <app-dir>
set -euo pipefail
PROXY="$1"; DOMAIN="$2"; APP_DIR="$3"
UPSTREAM="shitshpejt-web:3000"

NET="$(docker inspect -f '{{range $k, $v := .NetworkSettings.Networks}}{{$k}} {{end}}' "$PROXY" | awk '{print $1}')"
[ -n "$NET" ] || { echo "✗ Could not find the Docker network of $PROXY"; exit 1; }
echo "→ Using existing proxy $PROXY (network $NET)"

# 1. Our web container joins that network under a stable name.
cat > "$APP_DIR/compose.proxy.yaml" <<YAML
# Generated by make deploy: ports 80/443 belong to $PROXY, so we sit behind it.
services:
  web:
    networks:
      default: {}
      proxy:
        aliases: [shitshpejt-web]
networks:
  proxy:
    external: true
    name: $NET
YAML
docker rm -f shitshpejt-caddy-1 >/dev/null 2>&1 || true

# 2. Add our site to the proxy's Caddyfile (if it's a Caddy container with a mounted Caddyfile).
SRC="$(docker inspect -f '{{range .Mounts}}{{if or (eq .Destination "/etc/caddy/Caddyfile") (eq .Destination "/etc/caddy")}}{{.Source}}{{end}}{{end}}' "$PROXY")"
[ -d "$SRC" ] && SRC="$SRC/Caddyfile"
if [ -z "$SRC" ] || [ ! -f "$SRC" ]; then
  echo "⚠ Couldn't find $PROXY's Caddyfile. Add this to it yourself and reload it:"
  printf '\n%s {\n\tencode zstd gzip\n\treverse_proxy %s\n}\n\n' "$DOMAIN" "$UPSTREAM"
  exit 0
fi

if grep -qE "^[^#]*\b${DOMAIN//./\\.}\b.*\{" "$SRC"; then
  echo "→ $DOMAIN already in $SRC"
else
  cp "$SRC" "$SRC.bak-$(date +%F-%H%M%S)"
  printf '\n# ShitShpejt (added by make deploy)\n%s {\n\tencode zstd gzip\n\treverse_proxy %s\n}\n' "$DOMAIN" "$UPSTREAM" >> "$SRC"
  echo "→ Added $DOMAIN to $SRC (backup saved next to it)"
fi

if docker exec "$PROXY" caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null 2>&1; then
  docker exec "$PROXY" caddy reload --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null
  echo "✓ $PROXY reloaded, now also serving https://$DOMAIN"
else
  LAST="$(ls -t "$SRC".bak-* 2>/dev/null | head -1)"
  [ -n "$LAST" ] && cp "$LAST" "$SRC"
  echo "✗ The Caddyfile didn't validate, restored the backup. Your other site is untouched."
  docker exec "$PROXY" caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile || true
  exit 1
fi
